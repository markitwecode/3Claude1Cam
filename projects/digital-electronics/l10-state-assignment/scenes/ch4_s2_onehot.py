def _p(x, y):
    return np.array([x, y, 0.0])


# ---------------------------------------------------------------- shared: the corner strip
STRIP_LINES = [
    ["This is a shift register design style", "where only one FF at a time holds a 1"],
    ["Consequently we have 1 FF per state,", "compared with ⌈log₂ m⌉ for sequential", "assignment"],
    ["However, can result in simple", "fast state machines"],
    ["Outputs are generated by ORing", "together appropriate FF outputs"],
]


def bullet(lines, size=30, gap=0.06):
    """One slide bullet: a dot and left-aligned text lines. .dot .lines"""
    ls = VGroup(*[T(s, size) for s in lines]).arrange(DOWN, buff=gap, aligned_edge=LEFT)
    dot = T("•", size)
    dot.next_to(ls[0], LEFT, buff=0.2).set_y(ls[0].get_y())
    g = VGroup(dot, ls)
    g.dot, g.lines = dot, ls
    return g


def bullet_strip(size=28):
    bs = [bullet(ls, size, gap=0.08) for ls in STRIP_LINES]
    g = VGroup(*bs).arrange(DOWN, buff=0.22, aligned_edge=LEFT)
    g.to_corner(UL, buff=0.5)
    g.bullets = bs
    return g


# ---------------------------------------------------------------- this scene's pieces
S1 = load_scene("ch4_s1_hook")
S5 = load_scene("ch2_s5_ring")
H2 = load_scene("ch2_s1_hook")
H1 = load_scene("ch1_s1_hook")

MAIN_LINES = [
    ["This is a shift register design style", "where only one FF at a time holds a 1"],
    ["Consequently we have 1 FF per state, compared with", "⌈log₂ m⌉ for sequential assignment"],
    ["However, can result in simple fast state machines"],
    ["Outputs are generated by ORing together appropriate FF outputs"],
]

SIDE, PITCH = 0.9, 1.12
ROW_C = _p(-1.0, -0.3)          # clips 1-2: centre of the eight cells
ROW_C4 = _p(0.0, -1.3)           # clip 4
TAG_Y = 1.3
RING_SC = 0.5
RING_AT = _p(-5.0, -2.5)


def main_bullets():
    bs = [bullet(ls, 30) for ls in MAIN_LINES]
    g = VGroup(*bs).arrange(DOWN, buff=0.2, aligned_edge=LEFT)
    g.next_to(_p(-5.95, 2.85), DR, buff=0)
    return bs


def or_gate():
    g = H2.Gate(H2._or_body(), [(-0.71, 0.3), (-0.71, -0.3)], (0.7, 0.0), color=BLUE)
    return g.rotate(-PI / 2).scale(0.62)


def snap(old, new):
    """A flip-flop clocking: the digit changes in one step at the play's midpoint, so the cell is
    never empty and the two digits never overlap."""
    new.set_opacity(0)
    return [UpdateFromAlphaFunc(old, lambda m, a: m.set_opacity(0 if a >= 0.5 else 1)),
            UpdateFromAlphaFunc(new, lambda m, a: m.set_opacity(1 if a >= 0.5 else 0))]


def flip(mob, look, final):
    """Restyle mob in one step at the play's midpoint, on the same frame as snap()'s digit flip:
    look(mob, on) draws it lit (on=True) or unlit; it ends as `final`."""
    return UpdateFromAlphaFunc(mob, lambda m, a: look(m, bool(final) if a >= 0.5 else not final))


class OneHot(NarratedScene):
    def construct(self):
        self.clip1()
        self.clip2()
        self.clip3()
        self.clip4()
        self.wait(2.0)
        self.play(*[FadeOut(m) for m in self.mobjects], run_time=1.0)
        self.wait(0.15)

    # ------------------------------------------------------------ the row of eight
    def build_row(self):
        row = S1.onehot_row(8, 0, side=SIDE, pitch=PITCH).shift(ROW_C)
        row.clk_label.next_to(row.clk, LEFT, buff=0.15)
        self.row = row
        self.boxes = list(row.boxes)
        self.digs = list(row.digits)
        self.frame_parts = [row.clk, *row.stubs, row.wrap]
        self.hot, self.rs = 0, 1.0
        self.labels = None
        self.tag = None
        return row

    def unpack_row(self):
        self.remove(self.row)
        self.add(*self.frame_parts, *self.boxes, self.row.clk_label, *self.digs)

    def row_parts(self, with_frame=True):
        parts = self.boxes + self.digs
        return (self.frame_parts + parts) if with_frame else parts

    def row_move(self, k, center, parts):
        c0 = VGroup(*[b.copy() for b in self.boxes]).get_center()
        self.rs *= k
        return [m.animate.scale(k, about_point=c0).shift(center - c0) for m in parts]

    def row_step(self):
        s0, s1 = self.hot, (self.hot + 1) % 8
        anims = []
        for i, b in ((s0, 0), (s1, 1)):
            d = S1.hot_bit(b).scale(self.rs).move_to(self.boxes[i])
            anims += snap(self.digs[i], d)
            self._drop.append(self.digs[i])
            self.digs[i] = d
            anims.append(flip(self.boxes[i], lambda m, on: m.set_fill(GOLD, 0.22) if on else m.set_fill(BG, 1),
                              b))
        if self.tag is not None:
            x0, x1 = self.tag.get_x(), self.boxes[s1].get_x()
            anims.append(UpdateFromAlphaFunc(self.tag, lambda m, a: m.set_x(x1 if a >= 0.5 else x0)))
        if self.labels is not None:
            anims.append(flip(self.labels[s0], lambda m, on: m.set_color(FG if on else DIM), 0))
            anims.append(flip(self.labels[s1], lambda m, on: m.set_color(FG if on else DIM), 1))
        self.hot = s1
        return anims

    def play_step(self, rt):
        self._drop = []
        self.play(*self.row_step(), run_time=rt)
        self.remove(*self._drop)

    def row_ticks(self, c, cue, period=1.3, rt=0.7, first=None):
        if first is not None and c.until(cue, floor=0) >= first + 0.2:
            self.play_step(first)
            self.wait(0.3)
        while c.until(cue, floor=0) >= period:
            self.play_step(rt)
            self.wait(period - rt)

    # ------------------------------------------------------------ the small ring of five
    def ring_step(self):
        old = self.rbits
        new = [old[-1]] + old[:-1]
        anims = []
        for i in range(5):
            if new[i] != old[i]:
                d = S5.cell_bit(new[i], 56).scale(RING_SC).move_to(self.ring.boxes[i])
                anims += swap(self.rdig[i], d, shift=0.08 * UP)
                self.rdig[i] = d
                box = self.ring.boxes[i]
                anims.append(box.animate.set_fill(GOLD, 0.22) if int(new[i]) else box.animate.set_fill(BG, 1))
        self.rbits = new
        return anims

    # ------------------------------------------------------------ clips
    def clip1(self):
        title = T("One Hot State Encoding", 48).move_to(_p(0, 3.25))
        self.title = title
        row = self.build_row()
        trio = S1.binary_trio("000", side=0.6, pitch=0.72)
        for k, d in enumerate(trio.digits):
            nd = S1.hot_bit(0, 30).move_to(d)
            trio.remove(d)
            trio.add(nd)
            trio.digits[k] = nd
        trio.move_to(_p(5.55, ROW_C[1]))
        self.trio = trio
        btag = T("binary", 28, DIM).next_to(trio, DOWN, buff=0.22)
        self.btag = btag
        self.bul = main_bullets()
        with self.say("c4.onehot.1") as c:
            self.play(*appear(title), run_time=1.0)  # early: the slide title
            self.play(*appear(row, trio, btag, shift=None, lag=0.3), run_time=1.5)  # early: tag names the trio
            self.unpack_row()
            c.wait_until("only")
            self.play(*appear(self.bul[0]), run_time=1.0)  # early: the slide's bullet, voiced in paraphrase
            c.wait_until("hot one")
            tag = T("hot", 32, YELLOW).move_to(_p(self.boxes[0].get_x(), TAG_Y))
            self.tag = tag
            self.play(*appear(tag), FlashAround(self.digs[0], color=GOLD, run_time=1.2, time_width=1.5),
                      run_time=1.2)
            c.wait_until("as the machine steps")
            self.row_ticks(c, None, first=1.2)

    def clip2(self):
        ring = S5.ring_circle(center=ORIGIN, bits="00011")
        ring.remove(*ring.labels, *ring.digits)
        ring.digits = [S5.cell_bit(b, 56).move_to(ring.boxes[i]) for i, b in enumerate("00011")]
        ring.add(*ring.digits)
        ring.scale(RING_SC, about_point=ORIGIN).shift(RING_AT)
        self.ring, self.rbits = ring, list("00011")
        rtag = T("Part 2: two 1s", 30, t2c={"Part 2:": DIM, "1s": GOLD})
        rtag.next_to(ring, RIGHT, buff=0.45)
        exact = T("one-hot: exactly one 1", 36, t2c={"one-hot:": YELLOW, " 1": GOLD})
        exact.move_to(_p(ROW_C[0], -2.95))
        self.exact = exact
        clk_y = self.row.clk.get_y()
        labels = []
        for i in range(8):
            lab = VGroup(T("state", 28, DIM), T(str(i), 30, DIM)).arrange(DOWN, buff=0.08)
            lab.move_to(_p(self.boxes[i].get_x(), 0)).align_to(_p(0, clk_y - 0.3), UP)
            labels.append(lab)
        with self.say("c4.onehot.2") as c:
            self.play(*appear(ring, rtag, shift=None, lag=0.3), run_time=1.2)  # early: recap tag
            self.rdig = list(ring.digits)
            ring.remove(*self.rdig)
            self.add(*self.rdig)
            c.wait_until("part two's ring")
            while c.until("exactly", floor=0) >= 1.5:
                self.play(*self.ring_step(), run_time=0.7)
                self.wait(0.8)
            c.wait_until("exactly")
            self.play(*during(disappear(ring, *self.rdig, rtag), 0, 0.45),
                      *during(appear(exact), 0.5, 1), run_time=1.6)
            self.play(FlashAround(self.digs[self.hot], color=GOLD, run_time=1.2, time_width=1.5))
            c.wait_until("perstate")
            for i, lab in enumerate(labels):
                if i == self.hot:
                    for part in lab:
                        part.set_color(FG)
            self.play(*appear(*labels, lag=0.12), run_time=1.6)
            self.labels = [lab for lab in labels]
            self.row_ticks(c, "glance", period=1.4)
            c.wait_until("glance")
            ptr = label_pointer("state = where the 1 is", self.boxes[self.hot], UP, YELLOW, 32, 0.75)
            self.ptr = ptr
            self.play(*swap(self.tag, ptr[0]), GrowArrow(ptr[1]),
                      self.labels[self.hot].animate.set_color(YELLOW), run_time=1.4)
            self.tag = None
            self.play(FlashAround(self.labels[self.hot], run_time=1.2, time_width=1.5))

    def clip3(self):
        b2 = self.bul[1]
        col1 = T("sequential: ⌈log₂ m⌉", 36, t2c={"sequential:": DIM})
        col1.move_to(_p(-3.6, 0.2))
        col2 = T("one-hot: m", 36, t2c={"one-hot:": YELLOW})
        col2.move_to(_p(3.2, 0.2))
        m8 = T("m = 8", 40, t2c={"8": GOLD}).move_to(_p(0.35, 0.2))
        v3 = T("3", 60, GOLD).move_to(_p(-4.6, -1.3))
        v8 = T("8", 60, GOLD).move_to(_p(-0.35, -1.3))
        quote = H2.quote_card("“here we really are burning through the flip-flops”", size=34)
        quote[0].set_stroke(YELLOW, 3)
        quote.move_to(_p(0, -3.0))
        self.cols = [col1, col2, m8, v3, v8]
        self.quote = quote
        with self.say("c4.onehot.3") as c:
            going = [self.ptr, *self.labels, self.row.clk_label, self.exact]
            self.labels = None
            self.play(*during(disappear(*going), 0, 0.45),
                      *during(self.row_move(0.65, _p(3.5, -2.7), self.row_parts()), 0.45, 0.75),
                      *during([self.trio.animate.move_to(_p(-3.1, -2.7)),
                               self.btag.animate.move_to(_p(-3.1, -2.7 - 0.6))], 0.72, 1),
                      *during(appear(b2), 0.5, 1), run_time=2.4)  # early: the slide's bullet, voiced in paraphrase
            self.remove(self.row.clk_label)
            c.wait_until("log base two")
            self.play(*appear(col1), run_time=1.0)
            c.wait_until(own_word=col2)
            self.play(*appear(col2), run_time=1.0)
            c.wait_until("eight")
            self.play(*appear(m8), *disappear(self.btag), run_time=0.9)
            self.play(*during(self.row_move(1.0, _p(3.5, -1.3), self.row_parts()), 0, 0.55),
                      *during([self.trio.animate.move_to(_p(-3.1, -1.3))], 0, 0.55),
                      *during(appear(v3, v8, lag=0.2), 0.5, 1), run_time=1.8)
            c.wait_until("burn")
            self.play(*appear(quote), run_time=1.0)

    def clip4(self):
        q = T("?", 56, YELLOW)
        b3, b4 = self.bul[2], self.bul[3]
        q.move_to(_p(0, (b3.get_y() + b4.get_y()) / 2 - 0.05))
        with self.say("c4.onehot.4") as c:
            going = [self.quote, *self.cols, self.trio, *self.frame_parts]
            self.play(*during(disappear(*going), 0, 0.45),
                      *during(self.row_move(1 / 0.65, ROW_C4, self.row_parts(with_frame=False)), 0.35, 0.75),
                      *during(appear(q, shift=None), 0.75, 1), run_time=2.0)
            c.wait_until("simple")
            self.play(*swap(q, b3), run_time=1.2)  # early: the slide's bullet, voiced in paraphrase
            c.wait_until("outputs")
            self.play(*appear(b4), run_time=1.0)  # early: the slide's bullet, voiced in paraphrase

            gate = or_gate()
            gate.shift(_p(0, -3.1) - gate.out())
            wires = []
            for k, i in enumerate((5, 2)):            # inp(0) is on the right after the rotation
                top = self.boxes[i].get_bottom()
                end = gate.inp(k)
                ymid = (top[1] + end[1]) / 2 + 0.05
                w = VMobject().set_points_as_corners([top, _p(top[0], ymid), _p(end[0], ymid), end])
                wires.append(w.set_stroke(GREEN, 4))
            o = gate.out()
            out = VMobject().set_points_as_corners([o, o + 0.3 * DOWN, o + 0.3 * DOWN + 1.6 * RIGHT])
            out.set_stroke(GREEN, 4)
            out_lab = T("output", 30, GREEN).next_to(out.get_end(), RIGHT, buff=0.15)
            c.wait_until("joining")
            self.play(*[Create(w) for w in wires],
                      *[self.boxes[i].animate.set_stroke(GREEN, 5) for i in (2, 5)], run_time=1.5)
            c.wait_until("or gate")
            self.play(FadeIn(gate), run_time=0.8)
            self.play(Create(out), *appear(out_lab, shift=None), run_time=1.0)
            self.sketch = [gate, *wires, out, out_lab]

            c.wait_until("test")
            strip = bullet_strip()
            lamp = H1.lamp_column((0, 0, 0), scale=2.4)
            lamp.next_to(strip, RIGHT, buff=2.0).set_y(strip.get_y())
            leaving = [self.title, *self.bul[:2], b4, b3, *self.sketch, *self.boxes, *self.digs]
            self.play(*during([FadeOut(m, shift=0.3 * UP + 0.3 * LEFT) for m in leaving], 0, 0.45),
                      *during(appear(*strip.bullets, shift=None, lag=0.15), 0.5, 1),
                      run_time=1.6)  # early: the corner strip of bullets already read
            self.play(FadeIn(lamp, shift=0.2 * LEFT), run_time=0.8)
